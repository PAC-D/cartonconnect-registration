-- Run this once in the Supabase SQL Editor.
create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  registration_type text not null default 'Supplier' check (registration_type in ('Supplier', 'Factory')),
  supplier_code text,
  supplier_name text,
  factories jsonb not null check (jsonb_typeof(factories) = 'array' and jsonb_array_length(factories) > 0),
  suppliers jsonb not null default '[]'::jsonb check (jsonb_typeof(suppliers) = 'array'),
  full_name text not null check (char_length(full_name) between 2 and 120),
  email text not null check (char_length(email) <= 254),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

-- Upgrade existing installations created before factory registration was added.
alter table public.registrations
add column if not exists registration_type text not null default 'Supplier';

do $$
begin
  alter table public.registrations
  add constraint registrations_registration_type_check check (registration_type in ('Supplier', 'Factory'));
exception
  when duplicate_object then null;
end
$$;

-- Factory registrations can select several suppliers. Supplier rows keep supplier_code/name;
-- factory rows store their own factory in factories and the chosen suppliers in suppliers.
alter table public.registrations
add column if not exists suppliers jsonb not null default '[]'::jsonb;
alter table public.registrations alter column supplier_code drop not null;
alter table public.registrations alter column supplier_name drop not null;

update public.registrations
set suppliers = jsonb_build_array(jsonb_build_object('code', supplier_code, 'name', supplier_name)),
    supplier_code = null,
    supplier_name = null
where registration_type = 'Factory' and supplier_code is not null and suppliers = '[]'::jsonb;

do $$
begin
  alter table public.registrations
  add constraint registrations_shape_check check (
    (registration_type = 'Supplier' and supplier_code is not null and supplier_name is not null)
    or (registration_type = 'Factory' and jsonb_typeof(suppliers) = 'array' and jsonb_array_length(suppliers) > 0)
  );
exception
  when duplicate_object then null;
end
$$;

do $$
begin
  alter table public.registrations
  add constraint registrations_factory_count_check check (
    registration_type <> 'Factory' or jsonb_array_length(factories) = 1
  );
exception
  when duplicate_object then null;
end
$$;

alter table public.registrations enable row level security;

-- Keep the browser role insert-only. Neither public role can read registrations.
revoke all on table public.registrations from anon, authenticated;
grant insert on table public.registrations to anon;
revoke all on sequence public.registrations_id_seq from anon, authenticated;
grant usage on sequence public.registrations_id_seq to anon;

-- Anonymous visitors can submit registrations but cannot read them back.
do $$
begin
  create policy "Public can submit registrations"
  on public.registrations
  for insert
  to anon
  with check (
    status = 'pending'
    and registration_type in ('Supplier', 'Factory')
    and jsonb_typeof(factories) = 'array'
    and jsonb_array_length(factories) > 0
    and (registration_type <> 'Factory' or jsonb_array_length(factories) = 1)
  );
exception
  when duplicate_object then null;
end
$$;

-- Prevent duplicate submissions for the same registering supplier/factory and email.
-- If this fails while upgrading, an email registered the same factory more than once under
-- different suppliers; delete the duplicate rows and run the script again.
drop index if exists public.registrations_supplier_email_key;
drop index if exists public.registrations_type_supplier_email_key;
create unique index if not exists registrations_type_entity_email_key
on public.registrations (registration_type, coalesce(supplier_code, factories->0->>'code'), lower(email));

